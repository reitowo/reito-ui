import { mkdir, readFile, writeFile } from 'node:fs/promises';

// One maintained composition serves the Lab, Storybook, portable skill and package consumer test.
const source = await readFile('packages/ui/src/basic/composition-demo.tsx', 'utf8');
const body = source.slice(source.indexOf('/** Public components only:'));
const imports = `import { useId, useState } from 'react';
import {
  Stack, Inline, Grid, Text, Heading, Page, Panel, Button, Input, Field, FieldLabel,
  DashboardGroup, DashboardSidebar, DashboardSidebarHeader, DashboardSidebarContent,
  DashboardSidebarFooter, DashboardPanel, DashboardNavbar, DashboardNavigationMenu,
  Empty, EmptyHeader, EmptyTitle, EmptyDescription, ItemGroup, Item, ItemContent, ItemActions,
  ItemSeparator, SelectInput, Tabs, TabsList, TabsTrigger, TabsContent,
  ReitoThemeProvider, type DensityMode, type ThemeMode,
} from '@reito/ui/basic';

`;
const expected = '// Generated by scripts/sync-composition-recipe.mjs.\n' + imports + body;
const target = 'skills/reito-ui/assets/workbench.tsx';
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== expected) throw new Error('Run npm run recipe:build.');
} else {
  await mkdir('skills/reito-ui/assets', { recursive: true });
  await writeFile(target, expected);
}
console.log('Composition recipe uses public package imports and matches the maintained demo.');
