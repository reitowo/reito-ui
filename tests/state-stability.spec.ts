import { test, expect } from '@playwright/test';

for (const theme of ['dark','light']) for (const density of ['compact','comfortable']) {
  test('clear, select and short feedback keep component height: ' + theme + '/' + density, async ({ page }) => {
    await page.addInitScript(({ theme,density }) => {
      localStorage.setItem('reito-theme',theme);localStorage.setItem('reito-density',density);
      // This checks feedback geometry; the host clipboard is outside that contract.
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => undefined } });
    }, { theme,density });
    await page.goto('/?layer=basic&component=rating');
    const rating = page.locator('[data-slot="rating"]');
    const clear = rating.getByRole('button', { name:'清除本次回答质量' });
    const height = await rating.evaluate(node => node.getBoundingClientRect().height);
    const controls = page.locator('[data-slot="rating-controls"]');
    const rowHeight = await controls.evaluate(node => node.getBoundingClientRect().height);
    await clear.click();
    await expect(clear).toBeDisabled();
    await expect(rating.getByRole('radio').first()).toBeFocused();
    expect(await rating.evaluate(node => node.getBoundingClientRect().height)).toBe(height);
    expect(await controls.evaluate(node => node.getBoundingClientRect().height)).toBe(rowHeight);
    await rating.getByRole('radio',{name:'2 星，共 5 星'}).check({force:true});
    await expect(clear).toBeEnabled();
    expect(await rating.evaluate(node => node.getBoundingClientRect().height)).toBe(height);
    await rating.getByRole('radio',{name:'5 星，共 5 星'}).locator('..').hover();
    expect(await rating.evaluate(node => node.getBoundingClientRect().height)).toBe(height);
    await clear.hover();
    await expect(rating.locator('[data-slot="rating-item"][data-filled="true"]')).toHaveCount(2);
    await clear.click();
    await expect(rating.locator('[data-slot="rating-item"][data-filled="true"]')).toHaveCount(0);
    await rating.getByRole('radio',{name:'2 星，共 5 星'}).check({force:true});
    await page.mouse.move(0,0);
    await rating.screenshot({path:'.logs/rating-stable-' + theme + '-' + density + '.png'});
    await page.goto('/?layer=basic&component=listbox');
    const list = page.locator('[data-slot="listbox-field"]');
    const listHeight = await list.evaluate(node => node.getBoundingClientRect().height);
    const clearList = list.getByRole('button',{name:'清除',exact:true});
    await clearList.click();
    await expect(clearList).toBeDisabled();
    expect(await list.evaluate(node => node.getBoundingClientRect().height)).toBe(listHeight);
    await expect(list.getByRole('listbox')).toBeFocused();
    await page.goto('/?layer=basic&component=one-time-code');
    const code = page.locator('[data-slot="one-time-code"]');
    const codeHeight = await code.evaluate(node => node.getBoundingClientRect().height);
    await code.getByRole('button',{name:'复制JumpServer 验证码'}).click();
    await expect(code.getByText('已复制',{exact:true})).toBeVisible();
    expect(await code.evaluate(node => node.getBoundingClientRect().height)).toBe(codeHeight);
    await page.goto('/?layer=ai&component=message-actions');
    const actions = page.getByRole('group',{name:'消息操作'}).locator('..');
    const actionsHeight = await actions.evaluate(node => node.getBoundingClientRect().height);
    await actions.getByRole('button',{name:'有帮助',exact:true}).click();
    await expect(actions.getByText('反馈已记录')).toBeVisible();
    expect(await actions.evaluate(node => node.getBoundingClientRect().height)).toBe(actionsHeight);
    await actions.getByRole('button',{name:'有帮助',exact:true}).click();
    await expect(actions.getByText('反馈已撤回')).toBeVisible();
    expect(await actions.evaluate(node => node.getBoundingClientRect().height)).toBe(actionsHeight);
    await page.goto('/?layer=basic&component=multi-select');
    const chips = page.locator('[data-slot="combobox-chips"]');
    const chipHeight = await chips.evaluate(n => n.getBoundingClientRect().height);
    await page.getByRole('button',{name:'移除React'}).click();
    expect(await chips.evaluate(n => n.getBoundingClientRect().height)).toBe(chipHeight);
    await page.goto('/?layer=basic&component=calendar');
    const calendar = page.locator('[data-slot="calendar"]');
    const calendarHeight = await calendar.evaluate(n => n.getBoundingClientRect().height);
    for (let month=0; month<12; month++) {
      await calendar.getByRole('button',{name:'Go to the Previous Month'}).click();
      expect(await calendar.evaluate(n => n.getBoundingClientRect().height)).toBe(calendarHeight);
    }
    await page.goto('/?layer=ai&component=code-block');
    const copyCode = page.getByRole('button',{name:'复制代码',exact:true});
    const copyWidth = await copyCode.evaluate(n => n.getBoundingClientRect().width);
    await copyCode.click();
    const copiedCode = page.getByRole('button',{name:'代码已复制',exact:true});
    await expect(copiedCode).toBeVisible();
    expect(await copiedCode.evaluate(n => n.getBoundingClientRect().width)).toBe(copyWidth);
    await page.goto('/?layer=complex&component=settings-section');
    const settingsDemo = page.locator('[data-slot="settings-section"]').locator('..');
    const settingsHeight = await settingsDemo.evaluate(n => n.getBoundingClientRect().height);
    const saveSettings = page.getByRole('button',{name:'保存设置',exact:true});
    const saveWidth = await saveSettings.evaluate(n => n.getBoundingClientRect().width);
    await saveSettings.click();
    const savedSettings = page.getByRole('button',{name:'已保存',exact:true});
    await expect(savedSettings).toBeDisabled();
    expect(await savedSettings.evaluate(n => n.getBoundingClientRect().width)).toBe(saveWidth);
    expect(await settingsDemo.evaluate(n => n.getBoundingClientRect().height)).toBe(settingsHeight);
    await page.goto('/?layer=ai&component=permission');
    const permission = page.getByRole('region',{name:'权限请求：运行本地检查'});
    const permissionHeight = await permission.evaluate(node => node.getBoundingClientRect().height);
    await permission.getByRole('button',{name:'允许一次'}).click();
    await expect(permission.getByText('已允许',{exact:true})).toBeVisible();
    expect(await permission.evaluate(node => node.getBoundingClientRect().height)).toBe(permissionHeight);
  });
}
